package main

// CLI installer distribution (TASK-024): the gateway serves a POSIX
// curl-pipe-bash installer and the cross-built eap binaries from a dist
// directory. Endpoints are public by design — they ship the same public CLI
// binary — and never touch employee credentials or store layout. The origin
// is injected into the script per request; nothing origin-specific is
// committed.

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"enterprise-agent-platform/packages/errs"
)

// cliPlatforms is the allowlist of installable targets. Anything else —
// including anything that smells like a path — is refused.
var cliPlatforms = map[string]bool{
	"linux-amd64": true, "linux-arm64": true,
	"darwin-amd64": true, "darwin-arm64": true,
	"windows-amd64": true,
}

func (s *Server) cliDistEnabled() bool { return s.CLIDist != "" }

// handleCLIInstallScript serves the POSIX installer with the request origin
// injected. GET only, no auth, no caching of the origin-specific body.
func (s *Server) handleCLIInstallScript(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet || !s.cliDistEnabled() {
		writeProblem(w, r, errs.New(errs.NotFound, "cli installer is not available"))
		return
	}
	scheme := "http"
	if r.TLS != nil {
		scheme = "https"
	}
	if proto := r.Header.Get("X-Forwarded-Proto"); proto == "https" {
		scheme = "https"
	}
	origin := scheme + "://" + r.Host
	script := strings.ReplaceAll(cliInstallScriptTemplate, "{{ORIGIN}}", origin)
	w.Header().Set("Content-Type", "application/x-shellscript; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	_, _ = w.Write([]byte(script))
}

// cliBinaryPath resolves the dist file for a validated platform triple.
// The filename is constructed server-side from the allowlisted triple —
// request components never touch the path.
func (s *Server) cliBinaryPath(platform string) (string, bool) {
	if !cliPlatforms[platform] || !s.cliDistEnabled() {
		return "", false
	}
	name := "eap-" + platform
	if strings.HasSuffix(platform, "windows") {
		name += ".exe"
	}
	path := filepath.Join(s.CLIDist, name)
	if info, err := os.Stat(path); err != nil || !info.Mode().IsRegular() {
		return "", false
	}
	return path, true
}

// handleCLIInstallBinary serves one cross-built binary for an allowlisted
// platform with its sha256 digest header.
func (s *Server) handleCLIInstallBinary(w http.ResponseWriter, r *http.Request) {
	platform := r.PathValue("platform")
	path, ok := s.cliBinaryPath(platform)
	if !ok {
		writeProblem(w, r, errs.New(errs.NotFound, "no CLI binary for this platform"))
		return
	}
	data, err := os.ReadFile(path)
	if err != nil {
		writeProblem(w, r, errs.New(errs.Internal, "cli binary unreadable"))
		return
	}
	sum := sha256.Sum256(data)
	w.Header().Set("X-EAP-Sha256", hex.EncodeToString(sum[:]))
	w.Header().Set("Content-Type", "application/octet-stream")
	_, _ = w.Write(data)
}

// handleCLIChecksums serves a flat "sha256  filename" list the installer can
// verify against with plain shell tools.
func (s *Server) handleCLIChecksums(w http.ResponseWriter, r *http.Request) {
	if !s.cliDistEnabled() {
		writeProblem(w, r, errs.New(errs.NotFound, "cli installer is not available"))
		return
	}
	entries, err := os.ReadDir(s.CLIDist)
	if err != nil {
		writeProblem(w, r, errs.New(errs.Internal, "cli dist unreadable"))
		return
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		if e.Type().IsRegular() && strings.HasPrefix(e.Name(), "eap-") {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	var b strings.Builder
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(s.CLIDist, name))
		if err != nil {
			continue
		}
		sum := sha256.Sum256(data)
		fmt.Fprintf(&b, "%x  %s\n", sum, name)
	}
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	_, _ = w.Write([]byte(b.String()))
}

// handleCLIManifest publishes the installer contract as JSON for tooling.
func (s *Server) handleCLIManifest(w http.ResponseWriter, r *http.Request) {
	if !s.cliDistEnabled() {
		writeProblem(w, r, errs.New(errs.NotFound, "cli installer is not available"))
		return
	}
	platforms := make([]string, 0, len(cliPlatforms))
	for p := range cliPlatforms {
		platforms = append(platforms, p)
	}
	sort.Strings(platforms)
	writeJSON(w, http.StatusOK, map[string]any{
		"install_script": "/cli/install.sh",
		"platforms":      platforms,
	})
}

// cliInstallScriptTemplate is the committed installer source. It must stay
// POSIX-sh, credential-free, and verify checksums before activation.
const cliInstallScriptTemplate = `#!/bin/sh
# eap CLI installer — generated by the EAP gateway (origin injected per request).
set -eu
ORIGIN="{{ORIGIN}}"

OS=$(uname -s | tr '[:upper:]' '[:lower:]')
case "$OS" in linux|darwin) ;; *) echo "eap installer: unsupported os '$OS'" >&2; exit 1;; esac
ARCH=$(uname -m)
case "$ARCH" in
  x86_64|amd64) ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  *) echo "eap installer: unsupported arch '$ARCH'" >&2; exit 1 ;;
esac
PLATFORM="$OS-$ARCH"

if command -v curl >/dev/null 2>&1; then
  fetch() { curl -fsSL "$1" -o "$2"; }
elif command -v wget >/dev/null 2>&1; then
  fetch() { wget -qO "$2" "$1"; }
else
  echo "eap installer: need curl or wget" >&2; exit 1
fi
sum() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | cut -d' ' -f1
  else echo "eap installer: need sha256sum or shasum" >&2; exit 1; fi
}

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "downloading eap for $PLATFORM..."
fetch "$ORIGIN/cli/install/$PLATFORM" "$TMP/eap"
EXPECT=$(fetch "$ORIGIN/cli/install/sha256sums" "$TMP/sums" && grep "eap-$PLATFORM" "$TMP/sums" | cut -d' ' -f1)
if [ -z "$EXPECT" ]; then echo "eap installer: no checksum for $PLATFORM" >&2; exit 1; fi
ACTUAL=$(sum "$TMP/eap")
if [ "$ACTUAL" != "$EXPECT" ]; then
  echo "eap installer: checksum mismatch for $PLATFORM" >&2; exit 1
fi

DEST="${EAP_INSTALL_DIR:-$HOME/.eap/bin}"
mkdir -p "$DEST"
chmod +x "$TMP/eap"
mv "$TMP/eap" "$DEST/eap"

echo "installed: $DEST/eap"
case ":$PATH:" in
  *":$DEST:"*) ;;
  *) echo "note: $DEST is not in PATH; add: export PATH=\"$DEST:\$PATH\"""" ;;
esac
echo "next: run 'eap --help', then configure your gateway endpoint"
`
